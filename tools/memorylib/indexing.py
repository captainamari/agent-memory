from __future__ import annotations

import os
from pathlib import Path
from urllib.parse import quote

from .model import BEGIN, END, ROOTS, MemoryError, Store, safe_path


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").replace("\r", " ")


def index_directories(store: Store) -> list[Path]:
    directories = {store.root}
    for name in ROOTS:
        path = safe_path(store.root, name)
        if path.is_dir():
            directories.add(path)
            for child in path.rglob("*"):
                safe_path(store.root, child.relative_to(store.root).as_posix())
                if child.is_dir():
                    directories.add(child)
    return sorted(directories)


def expected_indices(store: Store) -> dict[str, str]:
    expected = {}
    dirs = index_directories(store)
    for directory in dirs:
        path = directory / "INDEX.md"
        relative = path.relative_to(store.root).as_posix()
        old = path.read_text(encoding="utf-8") if path.exists() else (
            f"# {directory.name if directory != store.root else 'agent-memory'}\n\n"
            "本页提供直接子目录与文档入口。正文与元数据保存在原文件中。\n\n" + BEGIN + "\n" + END + "\n")
        if old.count(BEGIN) != 1 or old.count(END) != 1 or old.index(BEGIN) > old.index(END):
            raise MemoryError(f"{relative}: exactly one ordered generated block is required")
        rows = [BEGIN, "", "<!-- Generated by tools/build_index.py; edit the prose outside this block. -->", ""]
        children = sorted(d for d in dirs if d.parent == directory and d != directory)
        if children:
            rows += ["| 子目录 | 说明 |", "| --- | --- |"]
            for child in children:
                title = store.domains.get(child.name, {}).get("title", child.name) if child.parent.name == "domains" else child.name
                detail = "候选区：不参与默认召回" if child.name == "inbox" else "历史区：仅显式历史查询" if child.name == "archive" else title
                rows.append(f"| [{cell(title)}]({quote(child.name)}/INDEX.md) | {cell(detail)} |")
            rows.append("")
        docs = sorted((d for d in store.documents if (store.root / d.path).parent == directory), key=lambda d: d.path)
        if docs:
            rows += ["| 文档 | ID / 类型 | 状态 | 摘要 |", "| --- | --- | --- | --- |"]
            for doc in docs:
                href = quote(Path(doc.path).name)
                rows.append(f"| [{cell(doc.meta.get('title', doc.id))}]({href}) | `{cell(doc.id)}` / {cell(doc.meta.get('type', ''))} | {cell(doc.meta.get('status', ''))} | {cell(doc.meta.get('summary', ''))} |")
            rows.append("")
        if not docs and not children:
            rows += ["暂无文档。", ""]
        rows.append(END)
        before = old[:old.index(BEGIN)]
        after = old[old.index(END) + len(END):]
        expected[relative] = before + "\n".join(rows) + after
    return expected


def build_indices(root: Path, check=False) -> list[str]:
    store = Store(root)
    if store.errors:
        raise MemoryError("Fix malformed documents before indexing: " + str(store.errors))
    changed = []
    for path, content in expected_indices(store).items():
        target = safe_path(store.root, path)
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            changed.append(path)
            if not check:
                temp = target.with_name(".memory-write-" + target.name)
                try:
                    temp.write_text(content, encoding="utf-8", newline="\n")
                    os.replace(temp, target)
                finally:
                    temp.unlink(missing_ok=True)
    return changed
